import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root=process.cwd();
const matrix=path.join(root,'docs','audits','SECURITY_REGRESSION_MATRIX.json');
const baseline=path.join(root,'docs','audits','SECURITY_REGRESSION_BASELINE.json');
const out=path.join(root,'docs','audits','SECURITY_REGRESSION_DIFF.json');
const hash=s=>crypto.createHash('sha256').update(s).digest('hex');
const current=JSON.parse(fs.readFileSync(matrix,'utf8'));
let previous=null;
if(fs.existsSync(baseline)) previous=JSON.parse(fs.readFileSync(baseline,'utf8'));
const map=r=>Object.fromEntries((r?.results||[]).map(x=>[x.name,x.reportStatus]));
const c=map(current), p=map(previous);
const names=[...new Set([...Object.keys(c),...Object.keys(p)])].sort();
const changes=names.filter(n=>c[n]!==p[n]).map(name=>({name,previous:p[name]||'MISSING',current:c[name]||'MISSING'}));
const regressions=changes.filter(x=>x.current==='FAIL'||x.current==='UNKNOWN'||(x.previous==='PASS'&&x.current!=='PASS'));
const report={generatedAt:new Date().toISOString(),status:regressions.length?'FAIL':(current.status==='EXTERNAL_REQUIRED'?'EXTERNAL_REQUIRED':'PASS'),baselinePresent:Boolean(previous),baselineSha256:previous?hash(fs.readFileSync(baseline,'utf8')):null,currentMatrixSha256:hash(fs.readFileSync(matrix,'utf8')),checkCount:current.checkCount,changes,regressions,rule:'Any transition from PASS to FAIL/UNKNOWN is a release-blocking regression. EXTERNAL_REQUIRED remains unresolved until real infrastructure evidence exists.'};
fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,JSON.stringify(report,null,2)+'\n');
console.log(`security-regression-diff: ${report.status} (${regressions.length} regressions, ${changes.length} changes)`);
if(report.status==='FAIL')process.exit(1);
